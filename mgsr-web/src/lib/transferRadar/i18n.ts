export type RadarT = (key: Key | (string & {}), vars?: Record<string, string | number>) => string;

export function useRadarT() {
  const { lang, isRtl } = useLanguage();
  const t: RadarT = useCallback((key, vars) => {
    const dict = (lang === 'he' ? HE : EN) as Record<string, string>;
    let s = dict[key] ?? (EN as Record<string, string>)[key] ?? String(key);
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.split('{' + a + '}').join(String(b));
    return s;
  }, [lang]);
  return { t, tr: t, lang, isRtl };
}
